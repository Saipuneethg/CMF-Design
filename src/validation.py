import os
import numpy as np
from src.spectral_reconstruction import SpectralReconstructor
from src.camera_model import CameraModel


class Validator:
    """
    Rigorously validates numerical metamer representations generated by Hit-and-Run:
    
    1. RGB Equality Residual:
       - r_i^{RGB} = ||A @ z_i - b||_2
       - Reconstructed measurement: c_hat_i = M @ R_i = M @ (mu + B @ z_i)
       - e_i^{RGB} = ||c_hat_i - c||_2
    2. Polytope Feasibility:
       - v_i = max_j (C_j @ z_i - d_j)
       - Tracks max violation, mean positive violation, percentage valid
    3. Multi-Chain Agreement:
       - Compares centroid, covariance, leading eigenvalues, and principal subspaces
       - Uses projection distance ||P_1 - P_2||_F / sqrt(2 * d) invariant to eigenvector signs
    4. Sample-Count Stability:
       - Tracks convergence of statistics across increasing sample counts
    """
    def __init__(
        self,
        artifacts_dir=None,
        A_camera=None,
        camera_offset=None,
        A_red=None,
        b_red=None,
        pca_basis=None,
        pca_mean=None,
        M_camera=None,
        camera_model=None
    ):
        if artifacts_dir is not None:
            self.A_red = np.load(os.path.join(artifacts_dir, "A_red.npy")).astype(np.float64)
            self.b_red = np.load(os.path.join(artifacts_dir, "b_red.npy")).astype(np.float64)
            self.reconstructor = SpectralReconstructor(artifacts_dir=artifacts_dir)
            if camera_model is not None:
                self.camera_model = camera_model
                self.A_camera, self.camera_offset = self.camera_model.project_pca(
                    self.reconstructor.pca_basis, self.reconstructor.pca_mean
                )
            else:
                self.A_camera = np.load(os.path.join(artifacts_dir, "A_camera.npy")).astype(np.float64)
                self.camera_offset = np.load(os.path.join(artifacts_dir, "camera_offset.npy")).astype(np.float64)
                self.camera_model = CameraModel.from_artifacts(artifacts_dir)
        else:
            self.A_camera = np.asarray(A_camera, dtype=np.float64)
            self.camera_offset = np.asarray(camera_offset, dtype=np.float64)
            self.A_red = np.asarray(A_red, dtype=np.float64)
            self.b_red = np.asarray(b_red, dtype=np.float64)
            self.reconstructor = SpectralReconstructor(pca_basis=pca_basis, pca_mean=pca_mean)
            self.camera_model = CameraModel(M=M_camera)

    def validate_points(self, rgb, z_points, tol=1e-5):
        """
        Validates a cloud of PCA coordinates against RGB equality and polytope inequalities.
        Preserves backward compatibility for app.py.
        """
        z_arr = np.asarray(z_points, dtype=np.float64)
        c_target = np.array(rgb, dtype=np.float64).flatten()
        b_eq = c_target - self.camera_offset

        # 1. RGB Equality Residual via PCA projection: A @ z - b
        residuals = np.linalg.norm(z_arr @ self.A_camera.T - b_eq, axis=1)
        mean_res = float(np.mean(residuals))
        max_res = float(np.max(residuals))
        rms_res = float(np.sqrt(np.mean(residuals ** 2)))

        # 2. RGB Verification via Reconstructed Spectra: c_hat = M @ R
        spectra = self.reconstructor.reconstruct(z_arr)
        c_pred = self.camera_model.measure(spectra)
        errors = np.linalg.norm(c_pred - c_target, axis=1)
        
        mean_error = float(np.mean(errors))
        max_error = float(np.max(errors))
        rms_error = float(np.sqrt(np.mean(errors ** 2)))

        # 3. Anchor feasibility residual for first point
        z0 = z_arr[0]
        anchor_residual = float(np.linalg.norm(self.A_camera @ z0 - b_eq))

        # 4. Polytope Membership Validation: A_red @ z <= b_red
        # Compute vector of max violations per point
        # Memory-efficient chunking to prevent multi-gigabyte RAM allocations
        violations = []
        chunk_size = 25
        for i in range(0, len(z_arr), chunk_size):
            chunk = z_arr[i : i + chunk_size]
            slacks = chunk @ self.A_red.T
            slacks -= self.b_red
            violations.extend(np.max(slacks, axis=1))
            del slacks

        violations = np.array(violations)
        max_violation = float(np.max(violations))
        pos_viols = violations[violations > 0]
        mean_pos_viol = float(np.mean(pos_viols)) if len(pos_viols) > 0 else 0.0
        
        valid_mask = violations <= tol
        valid_points = int(np.sum(valid_mask))
        total_points = len(z_arr)
        percent_valid = float((valid_points / max(total_points, 1)) * 100.0)

        # Detailed check statuses:
        status_reconstruction = "PASS" if max_error < 1e-4 else ("WARN" if max_error < 1e-2 else "FAIL")
        status_residual = "PASS" if max_res < 1e-5 else ("WARN" if max_res < 1e-3 else "FAIL")
        status_polytope = "PASS" if max_violation <= tol else ("WARN" if max_violation <= 1e-3 else "FAIL")
        overall_status = "PASS" if (status_reconstruction == "PASS" and status_residual == "PASS" and status_polytope == "PASS") else ("FAIL" if "FAIL" in [status_reconstruction, status_residual, status_polytope] else "WARN")

        return {
            "mean_error": mean_error,
            "max_error": max_error,
            "rms_error": rms_error,
            "mean_residual": mean_res,
            "max_residual": max_res,
            "rms_residual": rms_res,
            "constraint_residual": anchor_residual,
            "max_violation": max_violation,
            "mean_positive_violation": mean_pos_viol,
            "valid_points": valid_points,
            "total_points": total_points,
            "percent_valid": percent_valid,
            "all_valid_within_tolerance": bool(valid_points == total_points),
            "overall_status": overall_status,
            "checks": {
                "measurement_reconstruction": {
                    "status": status_reconstruction,
                    "measured": max_error,
                    "threshold": 1e-4,
                    "unit": "measurement-space (RGB units)",
                    "label": "Camera Measurement Reconstruction Error"
                },
                "equality_residual": {
                    "status": status_residual,
                    "measured": max_res,
                    "threshold": 1e-5,
                    "unit": "measurement-space (RGB units)",
                    "label": "Camera Equality Constraint Residual"
                },
                "polytope_membership": {
                    "status": status_polytope,
                    "measured": max_violation,
                    "threshold": tol,
                    "unit": "constraint units",
                    "label": "Spectral Polytope Feasibility"
                }
            },
            "units": {
                "errors": "RGB units (dimensionless [0-1])",
                "residuals": "RGB units (dimensionless [0-1])",
                "violations": "constraint units (reflectance prior space)",
                "valid_points": "samples",
                "percent_valid": "%"
            }
        }

    @staticmethod
    def compare_chains(chains_z, tol_dim=3):
        """
        Compares multiple independent Hit-and-Run chains in PCA coordinates.
        
        Evaluates:
        - Centroid discrepancy
        - Covariance relative Frobenius distance
        - Leading eigenvalues comparison
        - Subspace projection distance (invariant to sign flips)
        """
        num_chains = len(chains_z)
        if num_chains < 2:
            return {"status": "Need at least 2 chains for agreement analysis"}

        centroids = [np.mean(ch, axis=0) for ch in chains_z]
        covariances = [np.cov(ch, rowvar=False) for ch in chains_z]
        
        # Pairwise centroid distances
        centroid_dists = []
        cov_rel_diffs = []
        subspace_dists = []

        for i in range(num_chains):
            for j in range(i + 1, num_chains):
                # Centroid distance
                d_c = float(np.linalg.norm(centroids[i] - centroids[j]))
                centroid_dists.append(d_c)

                # Relative covariance difference: ||C_i - C_j||_F / ||C_i||_F
                f_diff = float(np.linalg.norm(covariances[i] - covariances[j], 'fro'))
                f_norm = float(np.linalg.norm(covariances[i], 'fro'))
                cov_rel_diffs.append(f_diff / max(f_norm, 1e-12))

                # Subspace distance for top principal directions:
                # Eigendecomposition of covariance:
                _, v_i = np.linalg.eigh(covariances[i])
                _, v_j = np.linalg.eigh(covariances[j])
                # Take top tol_dim eigenvectors
                u_i = v_i[:, -tol_dim:]
                u_j = v_j[:, -tol_dim:]
                # Projection matrices P = U @ U^T
                P_i = u_i @ u_i.T
                P_j = u_j @ u_j.T
                # Subspace metric: ||P_i - P_j||_F / sqrt(2 * tol_dim) in [0, 1]
                sub_dist = float(np.linalg.norm(P_i - P_j, 'fro') / np.sqrt(2.0 * tol_dim))
                subspace_dists.append(sub_dist)

        return {
            "num_chains": num_chains,
            "mean_centroid_distance": float(np.mean(centroid_dists)),
            "max_centroid_distance": float(np.max(centroid_dists)),
            "mean_covariance_rel_diff": float(np.mean(cov_rel_diffs)),
            "max_covariance_rel_diff": float(np.max(cov_rel_diffs)),
            "mean_subspace_distance": float(np.mean(subspace_dists)),
            "max_subspace_distance": float(np.max(subspace_dists)),
            "note": (
                "Subspace distance measures projection difference between leading principal directions, "
                "which is invariant to eigenvector sign reflections and near-repeated eigenvalue rotations."
            )
        }
